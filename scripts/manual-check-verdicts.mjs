#!/usr/bin/env node
// Gathers the verdicts agents wrote while playing docs/manual-checks.md
// (every results.jsonl under .scratch/manual-checks/) into
// docs/manual-checks-verdicts.md: what failed, what couldn't be judged and
// why, and what passed with the text each pass rests on. A test played more
// than once keeps its last verdict. A test no longer in the doc is dropped.
//
//   node scripts/manual-check-verdicts.mjs [--from .scratch/manual-checks] [--print]

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
let from = join(root, '.scratch', 'manual-checks')
let print = false
for (let i = 0; i < args.length; i += 1) {
  if (args[i] === '--from') from = resolve(args[++i])
  else if (args[i] === '--print') print = true
  else {
    console.error(`unknown argument ${args[i]}`)
    process.exit(2)
  }
}

/** Every results.jsonl under `dir`, oldest first, so a later run's verdict wins. */
function resultFiles(dir) {
  const found = []
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    const stat = statSync(path)
    if (stat.isDirectory()) found.push(...resultFiles(path))
    else if (name === 'results.jsonl') found.push({ path, at: stat.mtimeMs })
  }
  return found
}

const inDoc = new Set(
  readFileSync(join(root, 'docs', 'manual-checks.md'), 'utf8')
    .split(/\r?\n/)
    .filter((l) => l.startsWith('### '))
    .map((l) => l.slice(4).trim()),
)
const byTitle = new Map()
for (const { path } of resultFiles(from).sort((a, b) => a.at - b.at)) {
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    if (line.trim() === '') continue
    let row
    try {
      row = JSON.parse(line)
    } catch {
      continue
    }
    if (typeof row.title === 'string' && inDoc.has(row.title)) byTitle.set(row.title, row)
  }
}

const rows = [...byTitle.values()]
const of = (verdict) => rows.filter((r) => r.verdict === verdict).sort((a, b) => a.title.localeCompare(b.title, 'en'))
const oneLine = (text, max) => {
  const flat = String(text ?? '').replace(/\s+/g, ' ').trim()
  return flat.length > max ? `${flat.slice(0, max)} …` : flat
}
const evidence = (r, max) => oneLine((r.evidence ?? []).join(' ;; '), max)

const out = [
  '# Manual checks: what agents found',
  '',
  'Generated by `node scripts/manual-check-verdicts.mjs` from the verdicts Sonnet agents wrote while',
  'playing tests of `docs/manual-checks.md` through the text runner (`docs/plans/manual-checks-by-agents.md`).',
  'Nothing here has been deleted from the list: a **passed** test is one an agent saw match its Expect,',
  'with the text it saw quoted; delete it from the list once you trust the quote.',
  '',
  `${rows.length} tests played: ${of('passed').length} passed, ${of('failed').length} failed, ${of('cannot-judge').length} could not be judged.`,
  '',
  '## Failed',
  '',
  ...of('failed').map((r) => `- **${r.title}** — ${evidence(r, 400)}${r.note ? ` (${oneLine(r.note, 300)})` : ''}`),
  '',
  '## Could not be judged',
  '',
  ...of('cannot-judge').map((r) => `- **${r.title}** — ${oneLine(r.note || evidence(r, 240), 240)}`),
  '',
  '## Passed',
  '',
  ...of('passed').map((r) => `- **${r.title}** — ${evidence(r, 320)}`),
  '',
]
if (print) console.log(out.join('\n'))
else {
  const file = join(root, 'docs', 'manual-checks-verdicts.md')
  writeFileSync(file, out.join('\n'))
  console.log(`${file}: ${rows.length} tests (${of('passed').length} passed, ${of('failed').length} failed, ${of('cannot-judge').length} not judged)`)
}
