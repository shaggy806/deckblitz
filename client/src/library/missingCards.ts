/**
 * The library's "Not in the pool yet" list (the user, 2026-11-06): every
 * Commander-legal card the engine doesn't implement, from the static
 * `/missing-cards.json` that `npm run gen:missing-cards -w engine` writes out of
 * the Oracle snapshot (and `npm run verify` keeps current). Fetched only when
 * the filter is turned on: with each card's rules text (for the search, the
 * user, 2026-11-12) it is ~180 KB gzipped (~75 KB without), which the gallery
 * otherwise never needs.
 */

/** One row as the file stores it: `[name, printing, typeLine, colors,
 * edhrecRank | null, manaValue, text]`. `printing` is a Scryfall card id;
 * `text` is missing from a file written before it was added. */
type MissingRow = readonly [string, string, string, string, number | null, number, string?]

export interface MissingCard {
  readonly name: string
  /** A Scryfall card id: `resolveArtUrl` makes it the card's image. */
  readonly printing: string
  /** Every face's, " // " between them. */
  readonly typeLine: string
  /** Its colours as WUBRG letters, "" for colourless. */
  readonly colors: string
  readonly edhrecRank: number | null
  readonly manaValue: number
  /** Its Oracle rules text, every face's, a newline between them; searched,
   * not shown. */
  readonly text: string
}

/** The names a card answers to: its own, and each face's ("Fire // Ice" is
 * also "Fire" and "Ice"; a double-faced card's own name is both faces'). */
export function namesOfMissing(name: string): readonly string[] {
  const faces = name.split(' // ')
  return faces.length > 1 ? [name, ...faces] : [name]
}

/**
 * The file's cards, less any the pool now has (`inPool`): the file is
 * regenerated by verify, so it can be a batch behind the pool, and a card that
 * has landed since must not show as missing.
 */
export function parseMissingCards(json: unknown, inPool: (name: string) => boolean): readonly MissingCard[] {
  const rows = (json as { cards?: unknown } | null)?.cards
  if (!Array.isArray(rows)) throw new Error('missing-cards.json has no cards list')
  const out: MissingCard[] = []
  for (const row of rows as MissingRow[]) {
    const [name, printing, typeLine, colors, edhrecRank, manaValue, text = ''] = row
    if (namesOfMissing(name).some(inPool)) continue
    out.push({ name, printing, typeLine, colors, edhrecRank, manaValue, text })
  }
  return out
}

let loading: Promise<readonly MissingCard[]> | null = null

/** The list, fetched once a page; a failure isn't kept, so asking again
 * retries. */
export function fetchMissingCards(inPool: (name: string) => boolean): Promise<readonly MissingCard[]> {
  if (loading === null) {
    loading = fetch('/missing-cards.json')
      .then((res) => {
        if (!res.ok) throw new Error(`missing-cards.json: ${res.status}`)
        return res.json() as Promise<unknown>
      })
      .then((json) => parseMissingCards(json, inPool))
    loading.catch(() => {
      loading = null
    })
  }
  return loading
}
