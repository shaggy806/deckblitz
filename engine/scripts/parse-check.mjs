#!/usr/bin/env node
/**
 * `npm run card:parse-check -w engine [-- --all]`: the Oracle parser checked
 * against every authored card (`oracle-parse-check.mjs` has the comparison),
 * from the sources as they are now, without building `dist/`.
 *
 * The command had been `npm run build && node scripts/oracle-parse-check.mjs`:
 * ~40 s on a quiet machine and up to two minutes beside another agent's work,
 * nearly all of it `tsc` type-checking and emitting the engine when the check
 * reads only the card definitions and the card helpers. Agents building an
 * engine feature ran it four times a feature (2026-10-31). Now:
 *
 *  1. Every source file is read and hashed (~2 s for ~30,000 files, in
 *     parallel; reading them one at a time is ~8 s on Windows).
 *  2. `gen-cards.mjs` runs only if it would change something: its inputs (the
 *     card files, itself, the Oracle snapshot) hash to a key whose recorded
 *     outputs are not the generated files on disk now.
 *  3. The card barrel (`src/cards/generated.ts`) and the card helpers
 *     (`src/cards/helpers.ts`) are bundled from the sources with rolldown, the
 *     TypeScript stripped (the engine is `erasableSyntaxOnly`, so stripping is
 *     all `tsc`'s emit does to it), into a directory keyed on the hash of every
 *     source file; the parser's `../dist/cards/helpers.js` import is redirected
 *     to that bundle's helpers, so the parser and the definitions it is
 *     compared with come from the same sources.
 *  4. The report is cached under a key of the bundle's, the four scripts', the
 *     snapshot's and the flags' hashes.
 *
 * Every key is a content hash, never a modification time, so a stale cache
 * can't be read: any change to a source, a script or the snapshot is a new
 * key. The caches live in the OS temp dir (`mtg-engine-parse-check/`), the
 * newest few kept. `--no-cache` ignores them (it still writes them).
 *
 * What it no longer does is type-check: a type error the build would have
 * stopped on is `npm run typecheck`'s to report. Its report — stdout — is
 * byte for byte what `node scripts/oracle-parse-check.mjs` prints after a
 * build of the same tree; its own progress goes to stderr.
 */

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { registerHooks } from "node:module";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const engineDir = path.resolve(here, "..");
const srcDir = path.join(engineDir, "src");
const snapshotPath = path.join(engineDir, "data/oracle/cards.jsonl");
const cacheRoot = path.join(os.tmpdir(), "mtg-engine-parse-check");
const KEEP = 4;

const showAll = process.argv.includes("--all");
const noCache = process.argv.includes("--no-cache");
const t0 = Date.now();
const note = (s) => process.stderr.write(`parse-check: ${s} (${((Date.now() - t0) / 1000).toFixed(1)} s)\n`);

/** Generated by `gen-cards.mjs` from the card files: its outputs, not its inputs. */
const isGenerated = (rel) => rel === "cards/generated.ts" || rel === "cards/generated-index.ts" || rel.startsWith("cards/shards/");
/** What the bundle can't reach: tests, scaffold drafts, notes. */
const isSkipped = (rel) =>
  rel.startsWith("test/") || rel.startsWith("cards/scaffold/") || rel.endsWith(".test.ts") || rel.endsWith(".md") || rel.endsWith(".txt");

function listSources() {
  const out = [];
  (function walk(dir, rel) {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const r = rel === "" ? e.name : `${rel}/${e.name}`;
      if (e.isDirectory()) walk(path.join(dir, e.name), r);
      else if (!isSkipped(r)) out.push(r);
    }
  })(srcDir, "");
  return out.sort();
}

const sha = (data) => createHash("sha256").update(data).digest("hex");

/** A source's text with CRLF written LF: what it means is the same (a template
 * literal's line breaks are LF either way), and a checkout's CRLF copy of a
 * generated file `gen-cards.mjs` writes LF needn't cost a rebuild. */
const lf = (buf) => (buf.includes(13) ? buf.toString("utf8").replace(/\r\n/g, "\n") : buf);

/** Each source file's content hash, read many at a time. */
async function hashSources(rels) {
  const hashes = new Map();
  let next = 0;
  await Promise.all(
    Array.from({ length: 64 }, async () => {
      while (next < rels.length) {
        const rel = rels[next++];
        hashes.set(rel, sha(lf(await readFile(path.join(srcDir, rel)))));
      }
    }),
  );
  return hashes;
}

/** One key over the named files' hashes (names included) and some extra parts. */
function keyOf(hashes, rels, ...extra) {
  const h = createHash("sha256");
  for (const rel of rels) h.update(`${rel}\0${hashes.get(rel)}\n`);
  for (const part of extra) h.update(`\0${part}`);
  return h.digest("hex").slice(0, 32);
}

const fileHash = (file) => sha(readFileSync(file));

/** Keep the newest `KEEP` entries of a cache directory whose names start with `prefix`. */
function prune(prefix) {
  const entries = readdirSync(cacheRoot)
    .filter((n) => n.startsWith(prefix))
    .map((n) => ({ n, t: statSync(path.join(cacheRoot, n)).mtimeMs }))
    .sort((a, b) => b.t - a.t);
  for (const { n } of entries.slice(KEEP)) rmSync(path.join(cacheRoot, n), { recursive: true, force: true });
}

/** Write `file` whole or not at all (a concurrent run may be writing it too). */
function writeAtomic(file, data) {
  const tmp = `${file}.${process.pid}.tmp`;
  writeFileSync(tmp, data);
  renameSync(tmp, file);
}

mkdirSync(cacheRoot, { recursive: true });

const scriptsHash = sha(
  ["oracle-parse.mjs", "oracle-snapshot.mjs", "oracle-parse-check.mjs", "parse-check.mjs"].map((f) => fileHash(path.join(here, f))).join(),
);
const snapshotHash = existsSync(snapshotPath) ? fileHash(snapshotPath) : "none";
const genScriptHash = fileHash(path.join(here, "gen-cards.mjs"));

// 1-2. The generated card files, brought up to date only when they aren't.
let rels = listSources();
let hashes = await hashSources(rels);
const genInputs = rels.filter((r) => r.startsWith("cards/pool/") || r.startsWith("cards/tokens/"));
const genKey = keyOf(hashes, genInputs, genScriptHash, snapshotHash);
const genRecord = path.join(cacheRoot, `gen-${genKey}.txt`);
const outputsKey = () => keyOf(hashes, rels.filter(isGenerated));
if (noCache || !existsSync(genRecord) || readFileSync(genRecord, "utf8") !== outputsKey()) {
  note("running gen-cards");
  // The pool index it also refreshes is the authoring tools' (they rebuild it
  // when stale): up to 16 s this check doesn't need.
  const out = execFileSync(process.execPath, [path.join(here, "gen-cards.mjs")], {
    cwd: engineDir,
    encoding: "utf8",
    env: { ...process.env, GEN_CARDS_NO_POOL_INDEX: "1" },
  });
  process.stderr.write(out);
  rels = listSources();
  hashes = await hashSources(rels);
  writeAtomic(genRecord, outputsKey());
  prune("gen-");
} else note("generated card files up to date");

// 3. The definitions and the helpers, bundled from the sources.
const rolldownVersion = (() => {
  for (let dir = path.dirname(fileURLToPath(import.meta.resolve("rolldown"))); dir !== path.dirname(dir); dir = path.dirname(dir)) {
    const pkg = path.join(dir, "package.json");
    if (existsSync(pkg) && JSON.parse(readFileSync(pkg, "utf8")).name === "rolldown") return JSON.parse(readFileSync(pkg, "utf8")).version;
  }
  return "unknown";
})();
const bundleKey = keyOf(hashes, rels, fileHash(fileURLToPath(import.meta.url)), rolldownVersion, process.version);
const bundleDir = path.join(cacheRoot, `bundle-${bundleKey}`);

// 4. The report, if this exact check has been run.
const reportKey = sha([bundleKey, scriptsHash, snapshotHash, showAll ? "all" : "first-30"].join("\0")).slice(0, 32);
const reportFile = path.join(cacheRoot, `report-${reportKey}.txt`);
if (!noCache && existsSync(reportFile)) {
  note("report unchanged since its last run, from the cache");
  process.stdout.write(readFileSync(reportFile, "utf8"));
} else {
  if (noCache || !existsSync(path.join(bundleDir, "done"))) await bundle();
  else note("card definitions unchanged, bundle from the cache");

  // The parser imports the card helpers from `dist/`; point that at the
  // bundle's, and refuse any other `dist/` import rather than read a stale build.
  const distUrl = pathToFileURL(path.join(engineDir, "dist") + path.sep).href;
  const distHelpers = pathToFileURL(path.join(engineDir, "dist/cards/helpers.js")).href;
  const bundleHelpers = pathToFileURL(path.join(bundleDir, "helpers.js")).href;
  registerHooks({
    resolve(specifier, context, nextResolve) {
      if (context.parentURL !== undefined && (specifier.startsWith(".") || specifier.startsWith("file:"))) {
        const url = new URL(specifier, context.parentURL).href;
        if (url === distHelpers) return { url: bundleHelpers, shortCircuit: true, format: "module" };
        if (url.startsWith(distUrl)) throw new Error(`parse-check.mjs: ${context.parentURL} imports ${specifier} from dist/; bundle it from src/ here`);
      }
      return nextResolve(specifier, context);
    },
  });

  note("checking");
  const { POOL_CARDS } = await import(pathToFileURL(path.join(bundleDir, "generated.js")).href);
  const { reportLines } = await import("./oracle-parse-check.mjs");
  const report = reportLines(POOL_CARDS, showAll).map((l) => `${l}\n`).join("");
  writeAtomic(reportFile, report);
  prune("report-");
  process.stdout.write(report);
  note("done");
}

async function bundle() {
  note("bundling the card definitions from src/");
  const { rolldown } = await import("rolldown");
  const staging = `${bundleDir}.${process.pid}.tmp`;
  rmSync(staging, { recursive: true, force: true });
  const build = await rolldown({
    input: { generated: path.join(srcDir, "cards/generated.ts"), helpers: path.join(srcDir, "cards/helpers.ts") },
    platform: "node",
    // Every module evaluated, as the built barrel evaluates them.
    treeshake: false,
    // The engine's NodeNext imports name the emitted `.js`; the source is `.ts`.
    resolve: { extensionAlias: { ".js": [".ts", ".js"] } },
    logLevel: "warn",
  });
  await build.write({ dir: staging, format: "esm", entryFileNames: "[name].js", chunkFileNames: "[name]-[hash].js" });
  await build.close();
  writeFileSync(path.join(staging, "done"), "");
  rmSync(bundleDir, { recursive: true, force: true });
  try {
    renameSync(staging, bundleDir);
  } catch (err) {
    // Another run finished the same bundle first: theirs is the same content.
    if (!existsSync(path.join(bundleDir, "done"))) throw err;
    rmSync(staging, { recursive: true, force: true });
  }
  prune("bundle-");
}
