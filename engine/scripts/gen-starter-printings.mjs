// Writes `src/starter-printings.ts`: for each precon among the starter decks
// (`SAMPLE_DECKS` in `src/sample-decks.ts`), the Scryfall card id of the
// printing each card had in that precon — so a starter deck shows the art
// its real product did, rather than the pool's default printing.
//
//   node scripts/gen-starter-printings.mjs [--decks <dir>]
//
// Reads MTGJSON's per-deck files (https://mtgjson.com/downloads/all-decks/,
// one `<Name>_<SET>.json` per product), by default from the git-ignored
// `.scratch/precons/decks/` where the precon survey left them; a deck is
// matched by its MTGJSON `name`. Run after `npm run build -w engine` (it
// reads the deck names from `dist/`). A card keyed both ways — a split or
// double-faced card by its full "A // B" name and by its front face — so
// either spelling a deck list uses finds it. A precon with several printings
// of one name (its basic lands) keeps the first: decks bring one printing
// per name (`SavedDeck.printings`).

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { SAMPLE_DECKS } from "../dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const at = args.indexOf("--decks");
const dir = at >= 0 ? args[at + 1] : join(here, "..", "..", ".scratch", "precons", "decks");

const byName = new Map();
for (const file of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
  const data = JSON.parse(readFileSync(join(dir, file), "utf8")).data;
  if (data?.name !== undefined) byName.set(data.name, { file, data });
}

const out = {};
const missing = [];
for (const deck of SAMPLE_DECKS) {
  if (deck.printed === undefined) continue;
  const found = byName.get(deck.name);
  if (found === undefined) {
    missing.push(deck.name);
    continue;
  }
  const printings = {};
  const add = (name, id) => {
    if (id !== undefined && printings[name] === undefined) printings[name] = id;
  };
  for (const card of [...(found.data.commander ?? []), ...(found.data.mainBoard ?? [])]) {
    const id = card.identifiers?.scryfallId;
    add(card.name, id);
    if (card.name.includes(" // ")) add(card.name.split(" // ")[0], id);
  }
  // Only what the deck actually plays: a name the starter deck doesn't have
  // (a face key it spells the other way, a stand-in's original) is dropped.
  const plays = new Set([...(deck.commanders ?? []), ...deck.printed]);
  out[deck.name] = Object.fromEntries(Object.entries(printings).filter(([name]) => plays.has(name)).sort());
  const unprinted = [...plays].filter((name) => out[deck.name][name] === undefined);
  if (unprinted.length > 0) console.log(`${deck.name} (${found.file}): no printing for ${unprinted.join(", ")}`);
}
if (missing.length > 0) {
  console.error(`no MTGJSON deck named: ${missing.join(", ")}`);
  process.exit(1);
}

const body = Object.entries(out)
  .map(
    ([deck, printings]) =>
      `  ${JSON.stringify(deck)}: {\n${Object.entries(printings)
        .map(([name, id]) => `    ${JSON.stringify(name)}: ${JSON.stringify(id)},`)
        .join("\n")}\n  },`,
  )
  .join("\n");
const file = `// GENERATED by scripts/gen-starter-printings.mjs from MTGJSON's deck files —
// don't edit by hand. Rerun it when a starter deck changes.
//
// Each precon starter deck's printings: card name → the Scryfall card id of
// the printing it had in that product (\`SampleDeck.printings\`).

export const PRECON_PRINTINGS: Readonly<Record<string, Readonly<Record<string, string>>>> = {
${body}
};
`;
writeFileSync(join(here, "..", "src", "starter-printings.ts"), file);
console.log(`wrote src/starter-printings.ts: ${Object.keys(out).length} decks`);
