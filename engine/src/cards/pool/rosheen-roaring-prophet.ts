import { defineCard } from "../define.js";

// EDHREC rank 14532. Its mana ability reveals from the hand first, as Sacellum
// Godspeaker's does: the cards are chosen as it's activated (a mana ability
// can't stop to wait on the stack, rule 605.3b), any number including none,
// and {C}{C} is added for each. `"cost-with-x"` reads the cost actually being
// paid, as Rosheen Meanderer's does (the rulings).
//
// Rulings:
//   [2024-06-07] You can spend mana generated with Rosheen's last ability on any part of a cost that
//     contains {X}. You're not limited to spending it only on the {X} part.
//   [2024-06-07] A "cost that contains {X}" may be a spell's total cost, an activated ability's cost,
//     a suspend cost, or a cost you're asked to pay as part of the resolution of a spell or ability
//     (such as Condescend). A spell's total cost includes either its mana cost (printed in the upper
//     right corner) or its alternative cost (such as flashback), as well as any additional costs
//     (such as kicker). If it's something you can spend mana on, it's a cost. If that cost includes
//     the {X} symbol in it, you can spend mana generated by Rosheen on that cost.
//   [2024-06-07] You don't have to spend all of the mana generated with Rosheen's last ability on
//     the same cost.
//   [2024-06-07] You can use the mana generated with Rosheen's last ability in any cost you pay that
//     includes {X}, including the mana costs of spells, activation costs, and even costs for special
//     actions (such as morph). Any time you pay mana, that's a cost.
const ENTER_TEXT =
  "When Rosheen enters, mill six cards. You may put a card with {X} in its mana cost from among them into your hand.";
const SPEND_TEXT = "Spend this mana only on costs that contain {X}.";
const TAP_TEXT = `{T}: Reveal any number of cards with {X} in their mana cost in your hand. Add {C}{C} for each card revealed this way. ${SPEND_TEXT}`;

export default defineCard({
  name: "Rosheen, Roaring Prophet",
  manaCost: "{2}{R}{G}",
  colors: ["R", "G"],
  types: ["creature"],
  supertypes: ["legendary"],
  subtypes: ["Giant", "Shaman"],
  power: 4,
  toughness: 4,
  text: `${ENTER_TEXT}\n${TAP_TEXT}`,
  triggered: [
    {
      trigger: { on: "enters-battlefield", who: "self" },
      targets: [],
      effect: {
        kind: "sequence",
        effects: [
          { kind: "mill", target: "you", amount: 6 },
          {
            kind: "look-and-choose",
            zone: "graveyard",
            min: 0,
            max: 1,
            destination: "hand",
            leftover: "stay",
            filter: { thisWay: "milled", xInManaCost: true },
          },
        ],
      },
      resolve: null,
      text: ENTER_TEXT,
    },
  ],
  activated: [
    {
      cost: { mana: null, tap: true },
      targets: [],
      effect: {
        kind: "add-mana",
        mana: "C",
        amount: { product: [2, { thisWay: "revealed", who: "you" }] },
        first: {
          kind: "look-and-choose",
          zone: "hand",
          min: 0,
          max: { cardsInHand: "you" },
          filter: { xInManaCost: true },
          destination: "reveal",
          leftover: "stay",
        },
        spendOnly: { purposes: ["cost-with-x"], text: SPEND_TEXT },
      },
      resolve: null,
      text: TAP_TEXT,
    },
  ],
});
