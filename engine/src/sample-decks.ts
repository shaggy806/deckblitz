/**
 * The starter decks: real, format-legal 100-card Commander precons. First the
 * five Tarkir: Dragonstorm Commander decks (2025, MTGJSON set code `TDC`),
 * the bots' defaults since 2026-09-30; then
 * (2026-10-02) the five 2022 Starter Commander Decks (`SCD`) they replaced and
 * four more picked as nearest complete among WotC's Commander precons:
 * Tramplesaurus Rex and Reign of Dragons (`FDC`), Family Matters (`BLC`) and
 * World Shaper (`EOC`).
 *
 * **`bench`.** The bot tooling (`engine/scripts/bot-seating.mjs`) seats only
 * `BENCH_DECKS`, so a benchmark measures the bots on the same decks from one
 * run to the next; the rest are starter decks for players and bot seats. Flag
 * a deck once a deck-against-deck run shows it holds its own when identical
 * bots play it — a deck that loses every game measures nothing about a bot.
 * Since 2026-10-03 (the user's call, after `docs/plans/deck-autopsies.md`'s
 * re-run): Abzan Armor, Jeskai Striker, Reign of Dragons and Token Triumph.
 * Temur Roar (71%) and Mardu Surge (12.5%) stay starter decks but off the
 * bench; the two in their place keep a Dragon deck and a token deck on it.
 * Sultai Arisen rejoined on 2026-10-04 (21% in that day's re-run, its stand-ins
 * down from 25 to 1), and World Shaper joined on 2026-10-07 (29% once the bots
 * stopped stationing Hearthhull past its last threshold, from 6-12%), so the
 * bench is six decks.
 *
 * The bench decks are also the fallbacks: `SEATS` gives a seat nobody brought
 * a deck to — every bot's — the first four of them in this file's order.
 *
 * Two consumers: `server/src/decks.ts`'s `SEATS` (a room's fallback deck for
 * a seat nobody brought their own deck to, and every bot's deck) and the
 * client's deck builder (offered as ready-made "starter decks" to play as-is
 * or duplicate and edit) — lives here, in the engine, so both share one
 * source of truth instead of each keeping its own copy.
 *
 * **Substitutions.** Each deck's `printed` list is the decklist exactly as
 * printed. A card the engine doesn't implement yet is swapped out through that
 * deck's `substitutions` table rather than edited out of the list, so the
 * printed list stays the record of what the real deck is. Each substitute was
 * picked to stay inside the commander's colour identity, not duplicate a card
 * already in the deck (singleton), and fill the same role at a similar mana
 * value — a Dragon for a Dragon in Temur Roar, a wall for a wall in Abzan
 * Armor — see `docs/plans/precon-decks.md`.
 *
 * **To revert one** once its card is implemented, delete its entry from the
 * table. `sample-decks.test.ts` fails for any substitution whose original is
 * now implemented, so none can outlive the reason for it.
 */

import { PRECON_PRINTINGS } from "./starter-printings.js";
import { STRONG_DECK_DATA } from "./strong-decks.js";
import type { DeckCredit } from "./strong-decks.js";

export type { DeckCredit };

export interface PreconSubstitution {
  /** The printed card the engine doesn't implement yet. */
  readonly original: string;
  /** The implemented card playing in its slot. */
  readonly substitute: string;
  /** Why this card: the role it shares with the original. */
  readonly reason: string;
}

export interface SampleDeck {
  readonly name: string;
  /** In the bots' benchmark pool (`BENCH_DECKS`) — see the header. */
  readonly bench?: boolean;
  readonly commanders?: readonly string[];
  /** What the deck plays: `printed` with `substitutions` applied. */
  readonly cards: readonly string[];
  /** One line on what the deck does. */
  readonly description?: string;
  /** The 99 exactly as printed, for a real precon. */
  readonly printed?: readonly string[];
  readonly substitutions?: readonly PreconSubstitution[];
  /** For an upgraded deck (`UPGRADED_DECKS`): the starter deck it upgrades,
   * and what came out for what — its `cards` are that deck's with these
   * swapped in. */
  readonly upgradeOf?: string;
  readonly swaps?: readonly (readonly [cut: string, add: string])[];
  /** For a real player's deck (`STRONG_DECKS`): who built it, and where. */
  readonly credit?: DeckCredit;
  /** `false`: never dealt to a bot (`botPool`), because the bots pilot it too
   * badly to be an opponent. Still a starter deck a player can pick. */
  readonly bots?: false;
  /**
   * The printing each card had in the real product: card name → Scryfall
   * card id, as a saved deck's `printings` (the client's `SavedDeck`), so a
   * starter deck shows its precon's art. Generated into
   * `starter-printings.ts` from MTGJSON's deck files
   * (`scripts/gen-starter-printings.mjs`). Only the cards the deck plays: a
   * stand-in, and an upgraded deck's added card, has the pool's default
   * printing.
   */
  readonly printings?: Readonly<Record<string, string>>;
}

/** `printings` narrowed to the cards a deck plays (its commanders included). */
function printingsFor(
  printings: Readonly<Record<string, string>> | undefined,
  plays: readonly string[],
): Readonly<Record<string, string>> | undefined {
  if (printings === undefined) return undefined;
  const names = new Set(plays);
  const kept = Object.entries(printings).filter(([name]) => names.has(name));
  return kept.length > 0 ? Object.fromEntries(kept) : undefined;
}

const list = (entries: readonly (readonly [string, number])[]): string[] =>
  entries.flatMap(([name, count]) => Array<string>(count).fill(name));

const sub = (original: string, substitute: string, reason: string): PreconSubstitution => ({
  original,
  substitute,
  reason,
});

function precon(deck: {
  readonly name: string;
  readonly bench?: boolean;
  readonly commander: string;
  readonly description: string;
  readonly printed: readonly (readonly [string, number])[];
  readonly substitutions: readonly PreconSubstitution[];
}): SampleDeck {
  const printed = list(deck.printed);
  const swap = new Map(deck.substitutions.map((s) => [s.original, s.substitute]));
  for (const original of swap.keys()) {
    if (!printed.includes(original)) {
      throw new Error(`${deck.name}: substitution for ${original}, which isn't in the printed list`);
    }
  }
  const cards = printed.map((name) => swap.get(name) ?? name);
  const printings = printingsFor(PRECON_PRINTINGS[deck.name], [deck.commander, ...cards]);
  return {
    name: deck.name,
    ...(deck.bench === true ? { bench: true } : {}),
    commanders: [deck.commander],
    description: deck.description,
    printed,
    substitutions: deck.substitutions,
    cards,
    ...(printings !== undefined ? { printings } : {}),
  };
}

